"use server";

import { revalidatePath } from "next/cache";
import { after } from "next/server";
import { z } from "zod";

import { deliverFestivalNoticeCampaign } from "@/app/lib/festivals/reservations-open-notices";
import {
  countStandsAvailableAudiences,
  createStandsAvailableReminder,
  type StandsAvailableAudienceCounts,
} from "@/app/lib/festivals/stands-available-reminders";
import { requireAdminOrFestivalAdmin } from "@/app/lib/users/helpers";

/** What a send's own run may spend after answering; the crons have the rest. */
const DELIVERY_BUDGET_MS = 75_000;

const FestivalIdSchema = z.number().int().positive();
const SendInputSchema = z.object({
  festivalId: FestivalIdSchema,
  // Generated by the browser once per confirm dialog.
  requestId: z.uuid(),
  audience: z.enum(["terms_accepted", "all_eligible"]),
  channels: z.object({
    email: z.boolean(),
    inApp: z.boolean(),
    push: z.boolean(),
  }),
});

export type StandsAvailableAudienceResult =
  | { success: true; audiences: StandsAvailableAudienceCounts }
  | { success: false; message: string };

export type StandsAvailableSendResult =
  | {
      success: true;
      /** The same click arrived twice: nothing new went out. */
      alreadySent: boolean;
      recipients: number;
      emails: number;
      pushes: number;
    }
  | { success: false; message: string };

/** Who each audience of the reminder reaches right now. Counts only. */
export async function fetchStandsAvailableAudience(
  festivalId: number,
): Promise<StandsAvailableAudienceResult> {
  if (!(await requireAdminOrFestivalAdmin())) {
    return { success: false, message: "No autorizado" };
  }
  if (!FestivalIdSchema.safeParse(festivalId).success) {
    return { success: false, message: "Solicitud inválida" };
  }
  try {
    return {
      success: true,
      audiences: await countStandsAvailableAudiences(festivalId),
    };
  } catch (error) {
    console.error("Error counting the stands-available audience", {
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo calcular a quiénes se enviará el recordatorio.",
    };
  }
}

/**
 * Sends the "stands still available" reminder to participants who still
 * have a stand they could reserve, through the channels chosen in the
 * dialog. Every send is a new one: someone reminded before is reminded again.
 */
export async function sendStandsAvailableReminder(
  input: z.input<typeof SendInputSchema>,
): Promise<StandsAvailableSendResult> {
  const actor = await requireAdminOrFestivalAdmin();
  if (!actor) return { success: false, message: "No autorizado" };
  const parsed = SendInputSchema.safeParse(input);
  if (!parsed.success) {
    return { success: false, message: "Solicitud inválida" };
  }
  const { festivalId, requestId, audience, channels } = parsed.data;

  try {
    const result = await createStandsAvailableReminder({
      festivalId,
      audience,
      channels,
      requestId,
      actorUserId: actor.id,
      now: new Date(),
    });
    switch (result.kind) {
      case "not_found":
        return { success: false, message: "Festival no encontrado" };
      case "inactive":
        return {
          success: false,
          message: "Activa el festival antes de enviar el recordatorio.",
        };
      case "not_open":
        return {
          success: false,
          message: "Las reservas todavía no abrieron.",
        };
      case "invalid_channels":
        return { success: false, message: result.message };
      case "no_recipients":
        return {
          success: false,
          message:
            "No hay a quién enviarlo: nadie de este grupo tiene espacios disponibles para su categoría.",
        };
      case "duplicate":
        return {
          success: true,
          alreadySent: true,
          recipients: 0,
          emails: 0,
          pushes: 0,
        };
      case "sent":
        break;
    }

    const { campaignId } = result;
    after(async () => {
      try {
        await deliverFestivalNoticeCampaign(campaignId, {
          deadline: Date.now() + DELIVERY_BUDGET_MS,
        });
      } catch (error) {
        // What is left is the crons'.
        console.error("[stands-available] delivery failed", {
          campaignId,
          errorType: error instanceof Error ? error.name : typeof error,
        });
      }
    });
    revalidatePath(`/dashboard/festivals/${festivalId}`);
    return {
      success: true,
      alreadySent: false,
      recipients: result.recipients,
      emails: result.emails,
      pushes: result.pushes,
    };
  } catch (error) {
    console.error("Error sending the stands-available reminder", {
      festivalId,
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo enviar el recordatorio. Inténtalo nuevamente.",
    };
  }
}
