"use server";

import { revalidatePath } from "next/cache";
import { after } from "next/server";
import { z } from "zod";

import {
  countReservationsOpenAudience,
  createReservationsOpenNotice,
  deliverReservationsOpenNotice,
  type ReservationsOpenAudience,
} from "@/app/lib/festivals/reservations-open-notices";
import { requireAdminOrFestivalAdmin } from "@/app/lib/users/helpers";

/** What a send's own run may spend after answering; the crons have the rest. */
const DELIVERY_BUDGET_MS = 75_000;

const FestivalIdSchema = z.number().int().positive();
const ResendInputSchema = z.object({
  festivalId: FestivalIdSchema,
  // Generated by the browser once per confirm dialog.
  requestId: z.uuid(),
});

export type ReservationsOpenAudienceResult =
  | { success: true; audience: ReservationsOpenAudience }
  | { success: false; message: string };

export type ReservationsOpenSendResult =
  | {
      success: true;
      /** The same click arrived twice: nothing new went out. */
      alreadySent: boolean;
      recipients: number;
      emails: number;
      pushes: number;
    }
  | { success: false; message: string };

/** Who a resend would reach right now. Counts only. */
export async function fetchReservationsOpenAudience(
  festivalId: number,
): Promise<ReservationsOpenAudienceResult> {
  if (!(await requireAdminOrFestivalAdmin())) {
    return { success: false, message: "No autorizado" };
  }
  if (!FestivalIdSchema.safeParse(festivalId).success) {
    return { success: false, message: "Solicitud inválida" };
  }
  try {
    return {
      success: true,
      audience: await countReservationsOpenAudience(festivalId),
    };
  } catch (error) {
    console.error("Error counting the reservations-open audience", {
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo calcular a quiénes se enviará el aviso.",
    };
  }
}

/**
 * Sends the "reservations are open" notice again, to every participant it
 * reaches now, by email, in Glitter and as a push. Each resend is a new
 * send: people who got an earlier one get this one too.
 */
export async function resendReservationsOpenNotice(
  input: z.input<typeof ResendInputSchema>,
): Promise<ReservationsOpenSendResult> {
  const actor = await requireAdminOrFestivalAdmin();
  if (!actor) return { success: false, message: "No autorizado" };
  const parsed = ResendInputSchema.safeParse(input);
  if (!parsed.success) {
    return { success: false, message: "Solicitud inválida" };
  }
  const { festivalId, requestId } = parsed.data;

  try {
    const result = await createReservationsOpenNotice({
      festivalId,
      trigger: "manual",
      requestId,
      actorUserId: actor.id,
      now: new Date(),
    });
    switch (result.kind) {
      case "not_found":
        return { success: false, message: "Festival no encontrado" };
      case "inactive":
        return {
          success: false,
          message: "Activa el festival antes de enviar el aviso.",
        };
      case "not_open":
        return {
          success: false,
          message:
            "Las reservas todavía no abrieron: el aviso se enviará solo cuando abran.",
        };
      case "already_sent":
      case "duplicate":
        return {
          success: true,
          alreadySent: true,
          recipients: 0,
          emails: 0,
          pushes: 0,
        };
      case "sent":
        break;
    }

    const { campaignId } = result;
    after(async () => {
      try {
        await deliverReservationsOpenNotice(campaignId, {
          deadline: Date.now() + DELIVERY_BUDGET_MS,
        });
      } catch (error) {
        // What is left is the crons'.
        console.error("[reservations-open] resend delivery failed", {
          campaignId,
          errorType: error instanceof Error ? error.name : typeof error,
        });
      }
    });
    revalidatePath(`/dashboard/festivals/${festivalId}`);
    return {
      success: true,
      alreadySent: false,
      recipients: result.recipients,
      emails: result.emails,
      pushes: result.pushes,
    };
  } catch (error) {
    console.error("Error resending the reservations-open notice", {
      festivalId,
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo enviar el aviso. Inténtalo nuevamente.",
    };
  }
}
