"use server";

import { eq } from "drizzle-orm";
import { revalidatePath } from "next/cache";
import { after } from "next/server";
import { z } from "zod";

import { reservationsOpenChannelsProblem } from "@/app/lib/festivals/reservations-open-definitions";

import {
  countReservationsOpenAudience,
  createReservationsOpenNotice,
  deliverFestivalNoticeCampaign,
  type ReservationsOpenAudience,
} from "@/app/lib/festivals/reservations-open-notices";
import { requireAdminOrFestivalAdmin } from "@/app/lib/users/helpers";
import { db } from "@/db";
import { festivals } from "@/db/schema";

/** What a send's own run may spend after answering; the crons have the rest. */
const DELIVERY_BUDGET_MS = 75_000;

const FestivalIdSchema = z.number().int().positive();
const ChannelsSchema = z.object({
  email: z.boolean(),
  inApp: z.boolean(),
  push: z.boolean(),
});
const ResendInputSchema = z.object({
  festivalId: FestivalIdSchema,
  // Generated by the browser once per confirm dialog.
  requestId: z.uuid(),
  channels: ChannelsSchema,
});
const SettingsInputSchema = z.object({
  festivalId: FestivalIdSchema,
  auto: z.boolean(),
  channels: ChannelsSchema,
});

export type ReservationsOpenSettingsResult =
  | { success: true }
  | { success: false; message: string };

function festivalPath(festivalId: number) {
  return `/dashboard/festivals/${festivalId}`;
}

/**
 * Saves whether the notice goes out on its own when reservations open, and
 * through which channels. Archived festivals keep what they had.
 */
export async function updateReservationsOpenNoticeSettings(
  input: z.input<typeof SettingsInputSchema>,
): Promise<ReservationsOpenSettingsResult> {
  if (!(await requireAdminOrFestivalAdmin())) {
    return { success: false, message: "No autorizado" };
  }
  const parsed = SettingsInputSchema.safeParse(input);
  if (!parsed.success) {
    return { success: false, message: "Solicitud inválida" };
  }
  const { festivalId, auto, channels } = parsed.data;
  const problem = reservationsOpenChannelsProblem(channels);
  if (problem) return { success: false, message: problem };

  try {
    const [festival] = await db
      .select({ status: festivals.status })
      .from(festivals)
      .where(eq(festivals.id, festivalId));
    if (!festival) return { success: false, message: "Festival no encontrado" };
    if (festival.status === "archived") {
      return {
        success: false,
        message:
          "Este festival está archivado: sus ajustes ya no se pueden cambiar.",
      };
    }
    await db
      .update(festivals)
      .set({
        reservationsOpenNoticeAuto: auto,
        reservationsOpenNoticeEmail: channels.email,
        reservationsOpenNoticeInApp: channels.inApp,
        reservationsOpenNoticePush: channels.push,
        updatedAt: new Date(),
      })
      .where(eq(festivals.id, festivalId));
    revalidatePath(festivalPath(festivalId));
    return { success: true };
  } catch (error) {
    console.error("Error saving the reservations-open settings", {
      festivalId,
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo guardar la configuración. Inténtalo nuevamente.",
    };
  }
}

export type ReservationsOpenAudienceResult =
  | { success: true; audience: ReservationsOpenAudience }
  | { success: false; message: string };

export type ReservationsOpenSendResult =
  | {
      success: true;
      /** The same click arrived twice: nothing new went out. */
      alreadySent: boolean;
      recipients: number;
      emails: number;
      pushes: number;
    }
  | { success: false; message: string };

/** Who a resend would reach right now. Counts only. */
export async function fetchReservationsOpenAudience(
  festivalId: number,
): Promise<ReservationsOpenAudienceResult> {
  if (!(await requireAdminOrFestivalAdmin())) {
    return { success: false, message: "No autorizado" };
  }
  if (!FestivalIdSchema.safeParse(festivalId).success) {
    return { success: false, message: "Solicitud inválida" };
  }
  try {
    return {
      success: true,
      audience: await countReservationsOpenAudience(festivalId),
    };
  } catch (error) {
    console.error("Error counting the reservations-open audience", {
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo calcular a quiénes se enviará el aviso.",
    };
  }
}

/**
 * Sends the "reservations are open" notice again, to every participant it
 * reaches now, through the channels chosen in the dialog. Each resend is a
 * new send: people who got an earlier one get this one too.
 */
export async function resendReservationsOpenNotice(
  input: z.input<typeof ResendInputSchema>,
): Promise<ReservationsOpenSendResult> {
  const actor = await requireAdminOrFestivalAdmin();
  if (!actor) return { success: false, message: "No autorizado" };
  const parsed = ResendInputSchema.safeParse(input);
  if (!parsed.success) {
    return { success: false, message: "Solicitud inválida" };
  }
  const { festivalId, requestId, channels } = parsed.data;

  try {
    const result = await createReservationsOpenNotice({
      festivalId,
      trigger: "manual",
      requestId,
      actorUserId: actor.id,
      channels,
      now: new Date(),
    });
    switch (result.kind) {
      case "not_found":
        return { success: false, message: "Festival no encontrado" };
      case "inactive":
        return {
          success: false,
          message: "Activa el festival antes de enviar el aviso.",
        };
      case "not_open":
        return {
          success: false,
          message:
            "Las reservas todavía no abrieron: el aviso se enviará solo cuando abran.",
        };
      case "invalid_channels":
        return { success: false, message: result.message };
      case "disabled":
      case "too_late":
      case "already_sent":
      case "duplicate":
        return {
          success: true,
          alreadySent: true,
          recipients: 0,
          emails: 0,
          pushes: 0,
        };
      case "sent":
        break;
    }

    const { campaignId } = result;
    after(async () => {
      try {
        await deliverFestivalNoticeCampaign(campaignId, {
          deadline: Date.now() + DELIVERY_BUDGET_MS,
        });
      } catch (error) {
        // What is left is the crons'.
        console.error("[reservations-open] resend delivery failed", {
          campaignId,
          errorType: error instanceof Error ? error.name : typeof error,
        });
      }
    });
    revalidatePath(festivalPath(festivalId));
    return {
      success: true,
      alreadySent: false,
      recipients: result.recipients,
      emails: result.emails,
      pushes: result.pushes,
    };
  } catch (error) {
    console.error("Error resending the reservations-open notice", {
      festivalId,
      errorType: error instanceof Error ? error.name : typeof error,
    });
    return {
      success: false,
      message: "No se pudo enviar el aviso. Inténtalo nuevamente.",
    };
  }
}
